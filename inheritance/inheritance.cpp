#include <iostream>
using namespace std;

// Base class
class Employee {
  protected: // Protected access specifier
    int salary;
};

// Derived class
class Programmer: public Employee {
  public:
    int bonus;
    void setSalary(int s) {
      salary = s;
    }
    int getSalary() {
      return salary;
    }
};

int main() {
  Programmer myObj;
  myObj.setSalary(50000);
  myObj.bonus = 15000;
  cout << "Salary: " << myObj.getSalary() << "\n";
  cout << "Bonus: " << myObj.bonus << "\n";
  return 0;
}

// salary is protected, so it cannot be accessed directly from main().
// Only Employee and Programmer can access it.
// Therefore, we use public getter and setter functions to safely access and modify salary. This is an example of encapsulation.

