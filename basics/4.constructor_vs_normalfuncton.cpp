// Q: is constructor a member function of a class?

// ANS: Yes, constructor is a member function of a class. It is a special member function that is automatically called when an object of the class is created. It has the same name as the class and does not have a return type, not even void. It is used to initialize the object and can be overloaded to provide different ways of initializing objects.